/** Page icon sizes generated into public/industry-art/{slug}-{size}.webp (2× the CSS size). */
export const ICON_SIZES = [64, 160] as const;
export type IconSize = (typeof ICON_SIZES)[number];

export function industrySlug(name: string): string | null {
  return INDUSTRY_SLUGS[name] ?? null;
}

/** Absolute path of the 512px master, or null if this industry has none. */
export function industryArtMaster(name: string): string | null {
  const slug = industrySlug(name);
  if (!slug) return null;
  const file = join(process.cwd(), 'docs', 'design', 'art', 'industries', `${slug}.webp`);
  return existsSync(file) ? file : null;
}

/** Site-relative URL of a page icon, or null if it has not been generated. */
export function industryIconUrl(name: string, size: IconSize): string | null {
  const slug = industrySlug(name);
  if (!slug) return null;
  const rel = `industry-art/${slug}-${size}.webp`;
  return existsSync(join(process.cwd(), 'public', rel)) ? `/${rel}` : null;
}

/**
 * Site-relative URL of an industry share card (generated by scripts/og-pages.ts), or
 * null when it has not been generated — the caller then falls back to og-default.png
 * instead of Base.astro dropping og:image entirely for a missing file.
 */
export function industryOgPath(name: string): string | null {
  const slug = industrySlug(name);
  if (!slug) return null;
  const rel = `og/industry/${slug}.png`;
  return existsSync(join(process.cwd(), 'public', rel)) ? `/${rel}` : null;
}
