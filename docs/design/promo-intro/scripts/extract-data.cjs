#!/usr/bin/env node
/**
 * 哪家給最多 promo (intro) - real data extraction. Pure node, no dependencies.
 *
 * Reads the site's own build-time data and writes the handful of figures the animation
 * draws (a salary histogram, headline stats, TSMC's 7-year series). Nothing is typed in
 * by hand: re-running after a data refresh updates every number. The script only reports
 * mismatches against the numbers the storyboard quotes - it never "fixes" them.
 *
 * Usage    node scripts/extract-data.cjs
 * Input    <repo>/src/data/companies.json, market-stats.json, industries.json
 * Output   assets/data.json
 *
 * Units: *K fields are 仟元 (thousand NT$), exactly as in the source data
 *        (1,000 仟元 = 100 萬元 = NT$1,000,000); *Wan fields are 萬元 (= K / 10).
 */

const fs = require('fs');
const path = require('path');

const PROMO_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(PROMO_ROOT, '../../..');
const DATA_DIR = path.join(REPO_ROOT, 'src/data');
const OUT = path.join(PROMO_ROOT, 'assets/data.json');

const YEAR = '114'; // ROC year the film is about (companies.json meta.latestYear)

// Histogram bins, in 仟元: one bin per 100 (= 10 萬). Everything below LOW is folded into the
// first bin and everything at or above HIGH into the last, so the chart has 18 bars.
const BIN_K = 100;
const LOW_K = 400; // first bin  : medianK <  400  (< 40 萬)
const HIGH_K = 2000; // last bin   : medianK >= 2000 (>= 200 萬)

const readJson = (f) => JSON.parse(fs.readFileSync(path.join(DATA_DIR, f), 'utf8'));
const wan = (k) => (k == null ? null : Math.round(k) / 10);
const rocToCe = (y) => Number(y) + 1911;

const companiesFile = readJson('companies.json');
const marketStats = readJson('market-stats.json');
const industries = readJson('industries.json');

const meta = companiesFile.meta;
const companies = Object.values(companiesFile.companies);
if (String(meta.latestYear) !== YEAR) {
  console.warn(`WARNING: meta.latestYear is ${meta.latestYear}, this script is pinned to ${YEAR}`);
}

// ── 114 listed (sii) companies with a median ───────────────────────────────
// The market of a given year is the year row's own `market` (the homepage table does the same).
const siiRows = companies
  .map((c) => c.years[YEAR])
  .filter((y) => y && y.market === 'sii' && y.medianK != null);

// bins[0]: < 400 ; bins[i]: [400+100(i-1), 400+100i) ; last: >= 2000
const bins = [];
bins.push({ minK: null, maxK: LOW_K, label: `<${LOW_K / 10}` });
for (let lo = LOW_K; lo < HIGH_K; lo += BIN_K) {
  bins.push({ minK: lo, maxK: lo + BIN_K, label: `${lo / 10}-${(lo + BIN_K) / 10}` });
}
bins.push({ minK: HIGH_K, maxK: null, label: `>=${HIGH_K / 10}` });
for (const b of bins) {
  b.minWan = b.minK == null ? null : b.minK / 10;
  b.maxWan = b.maxK == null ? null : b.maxK / 10;
  b.count = 0;
}
for (const y of siiRows) {
  const v = y.medianK;
  const i = v < LOW_K ? 0 : v >= HIGH_K ? bins.length - 1 : 1 + Math.floor((v - LOW_K) / BIN_K);
  bins[i].count++;
}
const histTotal = bins.reduce((s, b) => s + b.count, 0);
const sii = marketStats[YEAR].sii;
const all = marketStats[YEAR].all;
const p50 = sii.medianP50;
const p50Bin = bins.findIndex((b) => (b.minK == null || p50 >= b.minK) && (b.maxK == null || p50 < b.maxK));

// Median of the very same list, to cross-check market-stats' medianP50 (not used as output).
const sorted = siiRows.map((y) => y.medianK).sort((a, b) => a - b);
const mid = sorted.length >> 1;
const recomputedMedian = sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;

// ── TSMC ───────────────────────────────────────────────────────────────────
const tsmcRec = companiesFile.companies['2330'];
const tsmc = {
  code: '2330',
  name: tsmcRec.name,
  industry: tsmcRec.industry,
  note: 'medianChangePct is null in the first year (no prior-year median).',
  years: Object.keys(tsmcRec.years)
    .sort()
    .map((y) => {
      const r = tsmcRec.years[y];
      return {
        year: Number(y),
        ce: rocToCe(y),
        medianK: r.medianK,
        medianWan: wan(r.medianK),
        avgK: r.avgK,
        avgWan: wan(r.avgK),
        medianChangePct: r.medianChangePct,
      };
    }),
};

// ── 114 company counts / year range ────────────────────────────────────────
const byYear = meta.counts.byYear;
const yearKeys = Object.keys(byYear).map(Number).sort((a, b) => a - b);
const with114 = companies.filter((c) => c.years[YEAR]).length;

const data = {
  _about:
    'Generated by scripts/extract-data.cjs from src/data/*.json. K = 仟元, Wan = 萬元. Do not edit by hand; re-run the script.',
  generatedFrom: { dataGeneratedAt: meta.generatedAt, latestYear: meta.latestYear },
  sii114Hist: {
    year: Number(YEAR),
    market: 'sii',
    unit: 'medianK (仟元); 100 仟元 = 10 萬 per bin',
    binRule: `Bin width ${BIN_K} 仟元 (10 萬). First bin folds everything below ${LOW_K} 仟元 (<${LOW_K / 10} 萬); last bin folds everything at or above ${HIGH_K} 仟元 (>=${HIGH_K / 10} 萬). Every bin is lower-inclusive, upper-exclusive.`,
    lowK: LOW_K,
    highK: HIGH_K,
    binWidthK: BIN_K,
    total: histTotal,
    minMedianK: sorted[0],
    maxMedianK: sorted[sorted.length - 1],
    recomputedMedianK: recomputedMedian,
    p50Bin, // index into bins of the bin that contains medianP50
    bins,
  },
  sii114: {
    year: Number(YEAR),
    companyCount: sii.companyCount,
    medianP25: sii.medianP25,
    medianP50: sii.medianP50,
    medianP75: sii.medianP75,
    medianP90: sii.medianP90,
    officialLabel: sii.official.label,
    officialAvgK: sii.official.avgK,
    officialEmployees: sii.official.employees,
  },
  all114: {
    year: Number(YEAR),
    companyCount: all.companyCount,
    medianP50: all.medianP50,
    companiesWithYear114: with114,
    totalCompanies: meta.counts.companies,
    byMarket: meta.counts.byMarket,
    byYear,
    firstYear: yearKeys[0],
    lastYear: yearKeys[yearKeys.length - 1],
    yearSpan: yearKeys.length,
    firstYearCe: rocToCe(yearKeys[0]),
    lastYearCe: rocToCe(yearKeys[yearKeys.length - 1]),
  },
  tsmc,
  industryCount: Object.keys(industries).length,
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(data, null, 2) + '\n');

// Embed the same JSON into index.html (<script id="promo-data">) so the composition stays
// self-contained (HyperFrames wants the timeline inline, built synchronously - no fetch).
const INDEX = path.join(PROMO_ROOT, 'index.html');
if (fs.existsSync(INDEX)) {
  const html = fs.readFileSync(INDEX, 'utf8');
  const re = /(<script id="promo-data" type="application\/json">)[\s\S]*?(<\/script>)/;
  if (re.test(html)) {
    const next = html.replace(re, (_, open, close) => `${open}\n${JSON.stringify(data)}\n    ${close}`);
    if (next !== html) fs.writeFileSync(INDEX, next);
    console.log(`embedded data into ${INDEX}`);
  } else {
    console.warn(`WARNING: no <script id="promo-data"> block in ${INDEX}; not embedded`);
  }
}

// ── summary: report, never adjust ──────────────────────────────────────────
const expect = (label, got, want) => {
  const ok = got === want;
  console.log(`${ok ? 'OK      ' : 'MISMATCH'}  ${label.padEnd(40)} got ${got}  (storyboard says ${want})`);
  return ok;
};
console.log(`wrote ${OUT}`);
console.log(`source data generatedAt ${meta.generatedAt}, latestYear ${meta.latestYear}\n`);
const checks = [
  expect('114 sii medianP50 (仟元)', sii.medianP50, 782),
  expect('114 sii official avgK (仟元)', sii.official.avgK, 1447),
  expect('114 all companyCount (market-stats)', all.companyCount, 1826),
  expect('114 companies with a year-114 row', with114, 1826),
  expect('total companies (meta.counts.companies)', meta.counts.companies, 1847),
];
console.log('');
console.log(`114 sii: market-stats companyCount ${sii.companyCount}, histogram total ${histTotal}, recomputed median ${recomputedMedian}, P25/P50/P75/P90 ${sii.medianP25}/${sii.medianP50}/${sii.medianP75}/${sii.medianP90}`);
console.log(`114 sii official: avgK ${sii.official.avgK}, employees ${sii.official.employees.toLocaleString('en-US')}`);
console.log(`year range: 民國 ${yearKeys[0]}-${yearKeys[yearKeys.length - 1]} (${rocToCe(yearKeys[0])}-${rocToCe(yearKeys[yearKeys.length - 1])}), ${yearKeys.length} years`);
console.log(`industries (industries.json keys): ${data.industryCount}`);
console.log(`histogram (${bins.length} bins, 萬): ${bins.map((b) => `${b.label}:${b.count}`).join('  ')}`);
console.log(`P50 ${p50} 仟元 falls in bin "${bins[p50Bin].label}" (index ${p50Bin})`);
console.log(`TSMC ${tsmc.years.map((y) => `${y.year}:${y.medianK}/${y.avgK}/${y.medianChangePct}`).join('  ')}  (year:medianK/avgK/medianChangePct)`);
if (!checks.every(Boolean)) console.log('\nNOTE: at least one storyboard number does not match the data. Data was NOT changed; report it.');
